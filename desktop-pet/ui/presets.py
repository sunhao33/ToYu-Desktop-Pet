"""时长预设的唯一定义处。

为什么单独成一个模块：原来主计时器（ui/timer_widget.py）和心流模式
（ui/flow_window.py）各写了一套预设，且上限不同 ——

    主计时器：1 / 3 / 5 / 10 / 15 / 25 / 30 / 45 / 60 分钟
    心流模式：25 / 45 / 60 / 90 分钟

用户看到的是"这个计时器最多只能到 1 小时""两边对不上"。
现在两处都从这里取，只有一份定义。

放在这里而不是 theme.py，是为了避免 flow_window <-> timer_widget
互相导入形成环。
"""

# 专注时长预设（分钟）。**固定 9 个** —— 主计时器用 3×3 网格排布，
# 数量变了会破坏那个布局。
# 取值覆盖三种场景：1~3 分钟用于快速试跑，10~45 是常见的专注段，
# 60/120 覆盖整段自习或写论文（原来最大只到 60，用户反馈"只能到 1 小时"）。
FOCUS_PRESETS = (1, 3, 5, 10, 15, 25, 30, 60, 120)

# 番茄钟"休息提醒间隔"预设（分钟）—— 这是提醒节律，不是计时时长，
# 所以单独一份，取值偏小。
POMODORO_PRESETS = (15, 25, 35, 45, 60)

# 自动回家（无互动超时）预设（分钟）
AUTO_HOME_PRESETS = (5, 10, 15, 30, 60)

# 自定义输入的小时上限（对应 23:59:59）
MAX_CUSTOM_HOURS = 23


